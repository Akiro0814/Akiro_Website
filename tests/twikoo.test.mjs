import { test } from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import path from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { createFixture } from './helpers/fixture.mjs';

process.env.TWIKOO_LOG_LEVEL = 'error';
test('异步审核写入与并发读写共享持久化互斥，退出会等待后置任务', async (t) => {
  const fixture = createFixture(t);
  const { createTwikooService } = await fixture.importModule('twikoo.mjs');
  const dataDir = path.join(fixture.root, 'data', 'twikoo');
  const service = createTwikooService({ dataDir, secret: 'isolated-test-secret', postSubmit: async (comment, context) => {
    await delay(20);
    await context.adapters.database.updateComment(String(comment._id), { isSpam: true });
  } });
  const replies = await Promise.all(Array.from({ length: 3 }, (_, i) => service.publicCall({ event: 'COMMENT_SUBMIT', url: '/notes/', nick: `并发读者${i}`, comment: '<p>异步审核</p>', ua: 'QA' }, { ip: `192.0.2.${i + 1}` })));
  assert.ok(replies.every((reply) => reply.body.code === 0));
  await service.close();
  const reopened = createTwikooService({ dataDir, secret: 'isolated-test-secret' });
  const documents = await reopened.documents();
  assert.equal(documents.length, 3);
  assert.ok(documents.every((comment) => comment.isSpam));
  await reopened.close();
});
test('官方 Twikoo 前台提交、后台审核与回复使用同一持久数据库，公开接口不能管理', async (t) => {
  const fixture = createFixture(t);
  const { createTwikooService } = await fixture.importModule('twikoo.mjs');
  const service = createTwikooService({ dataDir: path.join(fixture.root, 'data', 'twikoo'), secret: 'isolated-test-secret' });
  t.after(() => service.close());
  const version = await service.publicCall({ event: 'GET_FUNC_VERSION' });
  assert.ok(JSON.stringify(version.body).includes('2.0.15'));
  const posted = await service.publicCall({ event: 'COMMENT_SUBMIT', url: '/notes/', nick: '真实 SDK 读者', mail: 'visitor@example.com', comment: '<p>官方评论测试</p>', ua: 'QA' });
  assert.equal(posted.body.code, 0, JSON.stringify(posted));
  const id = posted.body.id;
  assert.ok(id);
  const publicList = await service.publicCall({ event: 'COMMENT_GET', url: '/notes/' });
  assert.equal(publicList.body.data[0].id, id);
  assert.equal('mail' in publicList.body.data[0], false);
  assert.equal('ip' in publicList.body.data[0], false);
  assert.equal((await service.publicCall({ event: 'COMMENT_DELETE_FOR_ADMIN', id })).status, 403);
  assert.equal((await service.publicCall({ event: 'SET_PASSWORD', password: 'attempt' })).status, 403);
  assert.equal((await service.publicCall({ event: 'COMMENT_DELETE_FOR_USER', id, accessToken: 'another-user' })).body.code, 1000);
  const reply = await service.adminCall({ event: 'COMMENT_SUBMIT', url: '/notes/', rid: id, pid: id, nick: 'Akiro', mail: 'blogger@localhost.invalid', comment: '<p>后台回复</p>', ua: 'admin' });
  assert.equal(reply.body.code, 0, JSON.stringify(reply));
  assert.equal('accessToken' in reply.body, false);
  const exported = await service.adminCall({ event: 'COMMENT_EXPORT_FOR_ADMIN' });
  const bridge = crypto.createHmac('sha256', 'isolated-test-secret').update('Akiro/Twikoo/admin/v1').digest('hex');
  assert.equal(JSON.stringify(exported.body).includes(bridge), false);
  const thread = await service.publicCall({ event: 'COMMENT_GET', url: '/notes/' });
  assert.equal(thread.body.data[0].replies[0].master, true);
  await service.adminCall({ event: 'COMMENT_SET_FOR_ADMIN', id, set: { isSpam: true } });
  assert.equal((await service.publicCall({ event: 'COMMENT_GET', url: '/notes/' })).body.data.length, 0);
  const admin = await service.adminCall({ event: 'COMMENT_GET_FOR_ADMIN', per: 100, page: 1, type: 'HIDDEN' });
  assert.equal(admin.body.count, 1);
  assert.equal(String(admin.body.data[0]._id), id);
  const config = await service.adminCall({ event: 'GET_CONFIG_FOR_ADMIN' });
  assert.equal('ADMIN_PASS' in config.body.config, false);
  assert.equal('AKIRO_MANAGED' in config.body.config, false);
});

test('旧评论与楼中楼幂等迁移，重启后保留审核状态和删除结果且不改旧文件', async (t) => {
  const fixture = createFixture(t);
  const { createTwikooService } = await fixture.importModule('twikoo.mjs');
  const original = [{ id: 'legacy-top', nick: '旧读者', url: '/posts/中文/', comment: '<p>旧评论</p>', created: 1700000000000, status: 'visible', like: 3 }, { id: 'legacy-reply', nick: '回复者', url: '/posts/中文/', comment: '<p>旧回复</p>', pid: 'legacy-top', rid: 'legacy-top', created: 1700000001000, status: 'visible' }];
  const before = JSON.stringify(original);
  const options = { dataDir: path.join(fixture.root, 'data', 'twikoo'), secret: 'isolated-test-secret', legacyComments: () => original };
  let service = createTwikooService(options);
  t.after(() => service.close());
  const thread = await service.publicCall({ event: 'COMMENT_GET', url: '/posts/中文/' });
  assert.equal(thread.body.data[0].replies[0].id, 'legacy-reply');
  assert.equal(thread.body.data[0].ups, 3);
  await service.adminCall({ event: 'COMMENT_DELETE_FOR_ADMIN', id: 'legacy-reply' });
  await service.adminCall({ event: 'COMMENT_SET_FOR_ADMIN', id: 'legacy-top', set: { isSpam: true } });
  await service.close();
  service = createTwikooService(options);
  const saved = await service.documents();
  assert.equal(saved.length, 1);
  assert.equal(saved[0].isSpam, true);
  assert.equal(JSON.stringify(original), before);
});
