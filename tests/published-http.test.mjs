import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import net from 'node:net';
import { test } from 'node:test';
import { setTimeout as delay } from 'node:timers/promises';
import { request, chromium } from '@playwright/test';
import { startPreview } from '../scripts/preview-admin.mjs';

test('真实 HTTP 发布隔离、构建中写入、失败、资源保留、评论和回滚一致，媒体入口可用', { timeout: 60000 }, async (t) => {
  const probe = net.createServer();
  await new Promise((resolve) => probe.listen(0, '127.0.0.1', resolve));
  const port = probe.address().port;
  await new Promise((resolve) => probe.close(resolve));
  const preview = startPreview({ port, quiet: true });
  t.after(() => preview.stop());
  fs.mkdirSync(path.join(preview.sandbox, 'src/data'), { recursive: true });
  fs.writeFileSync(path.join(preview.sandbox, 'src/data/site.config.json'), '{"githubUser":""}');
  fs.writeFileSync(path.join(preview.sandbox, 'package.json'), '{"type":"module","scripts":{"build":"node fixture-build.mjs"}}');
  fs.writeFileSync(path.join(preview.sandbox, 'fixture-build.mjs'), `
    import fs from 'node:fs';
    await new Promise(resolve => setTimeout(resolve, 250));
    fs.mkdirSync('dist', { recursive: true });
    fs.cpSync('public', 'dist', { recursive: true });
    fs.writeFileSync('dist/index.html', 'fixture');
    fs.writeFileSync('dist/search.json', '[]');
  `);
  for (let i = 0; i < 100; i++) {
    try { if ((await fetch(`${preview.url}/admin/login`)).ok) break; } catch {}
    await delay(100);
  }
  const client = await request.newContext({ baseURL: preview.url });
  t.after(() => client.dispose());
  const html = await (await client.get('/admin/login')).text();
  let csrf = JSON.parse(html.match(/window\.__BOOT__ = (\{[^;]+\});/)[1]).csrfToken;
  const logged = await client.post('/api/login', { headers: { 'X-CSRF-Token': csrf }, data: { username: 'preview', password: 'visual-preview-only' } });
  csrf = (await logged.json()).csrfToken;
  const post = (url, data) => client.post(url, { headers: { 'X-CSRF-Token': csrf }, data });
  const get = async (url) => (await client.get(url)).json();
  assert.equal((await fetch(`${preview.url}/api/media/references?name=cover.png`)).status, 401);
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
  const uploaded = await client.post('/api/upload?filename=封面.png', { headers: { 'X-CSRF-Token': csrf, 'Content-Type': 'application/octet-stream' }, data: png });
  const media = await uploaded.json();
  assert.ok(media.url);
  assert.equal((await fetch(preview.url + media.url)).status, 404);
  assert.equal((await client.get(`/api/media/preview/${encodeURIComponent(media.name)}`)).status(), 200);
  await post('/api/manage/profile', { profile: { hero: { backgroundUrl: media.url } } });
  await post('/api/manage/site-meta', { since: '2020-01-01' });
  fs.mkdirSync(path.join(preview.sandbox, 'data/music-files'));
  fs.writeFileSync(path.join(preview.sandbox, 'data/music-files/test.wav'), '0123456789');
  fs.writeFileSync(path.join(preview.sandbox, 'data/music.json'), JSON.stringify({ tracks: [{ id: 'local', source: 'local', title: '旧歌曲', fileName: 'test.wav', enabled: true }] }));
  fs.writeFileSync(path.join(preview.sandbox, 'data/friends.json'), JSON.stringify({ notice: '申请须知', items: [{ id: 'friend', status: 'approved', name: '朋友', url: 'https://example.org', email: 'private-friend@example.com' }] }));
  assert.deepEqual((await get('/api/public/playlist')).tracks, []);
  const publication = post('/api/build', {});
  for (let i = 0; i < 100 && !fs.existsSync(path.join(preview.sandbox, '.build-lock')); i++) await delay(10);
  assert.equal((await post('/api/manage/site-meta', { since: '2021-01-01' })).status(), 409);
  const frozenMeta = path.join(preview.sandbox, '.build-lock/workspace/data/site-meta.json');
  for (let i = 0; i < 100 && !fs.existsSync(frozenMeta); i++) await delay(10);
  assert.equal(fs.existsSync(frozenMeta), true);
  fs.writeFileSync(path.join(preview.sandbox, 'data/site-meta.json'), '{"since":"2021-01-01"}');
  const first = await (await publication).json();
  assert.equal(first.ok, true, first.log || first.message);
  assert.equal((await get('/api/public/site-stats')).since, '2020-01-01');
  assert.equal((await get('/api/public/playlist')).tracks[0].title, '旧歌曲');
  assert.equal((await fetch(preview.url + media.url)).status, 200);
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ storageState: await client.storageState(), viewport: { width: 1280, height: 900 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (err) => errors.push(err.message));
    await page.goto(`${preview.url}/admin/media`);
    await page.waitForLoadState('networkidle');
    await page.locator('[data-media-usage] summary').click();
    await page.getByText('当前线上：', { exact: false }).waitFor();
    assert.match(await page.locator('.media-usage__body').innerText(), /待发布内容[\s\S]*hero.backgroundUrl[\s\S]*当前线上/);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForTimeout(200);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    assert.deepEqual(errors, []);
    await context.close();
  } finally { await browser.close(); }
  assert.equal((await post('/api/media/delete', { name: media.name })).status(), 409);
  await post('/api/manage/profile', { profile: { hero: { backgroundUrl: '' } } });
  assert.equal((await post('/api/media/delete', { name: media.name })).status(), 200);
  await post('/api/manage/music/delete', { id: 'local' });
  await post('/api/manage/site-meta', { since: '2022-01-01' });
  await post('/api/manage/announcements/save', { id: 'preview-ann', title: '新公告', enabled: true });
  const submitted = await post('/api/public/twikoo', { event: 'COMMENT_SUBMIT', url: '/notes/', nick: '新读者', comment: '<p>等待发布</p>', ua: 'Isolated QA' });
  const submittedBody = await submitted.json();
  assert.equal(submittedBody.code, 0, JSON.stringify(submittedBody));
  assert.equal((await (await post('/api/public/twikoo', { event: 'COMMENT_GET', url: '/notes/' })).json()).data.length, 0);
  assert.equal((await get('/api/public/site-stats')).since, '2020-01-01');
  assert.equal((await get('/api/public/announcements')).items[0].title, '欢迎来到博客');
  assert.equal((await fetch(preview.url + media.url)).status, 200);
  const audio = await client.get('/api/music/file/test.wav', { headers: { Range: 'bytes=2-4' } });
  assert.equal(audio.status(), 206);
  assert.equal((await audio.body()).toString(), '234');
  assert.equal((await client.get('/api/public/playlist/resolve/unpublished')).status(), 404);
  fs.writeFileSync(path.join(preview.sandbox, 'fixture-build.mjs'), 'process.exit(1)');
  assert.equal((await (await post('/api/build', {})).json()).ok, false);
  assert.equal((await get('/api/public/site-stats')).since, '2020-01-01');
  fs.writeFileSync(path.join(preview.sandbox, 'fixture-build.mjs'), `import fs from 'node:fs';fs.mkdirSync('dist');fs.cpSync('public','dist',{recursive:true});fs.writeFileSync('dist/search.json','[]');`);
  const second = await (await post('/api/build', {})).json();
  assert.equal(second.ok, true, second.log || second.message);
  assert.equal((await get('/api/public/site-stats')).since, '2022-01-01');
  assert.equal((await get('/api/public/announcements')).items[0].title, '新公告');
  assert.deepEqual((await get('/api/public/playlist')).tracks, []);
  assert.equal((await (await post('/api/public/twikoo', { event: 'COMMENT_GET', url: '/notes/' })).json()).data.length, 1);
  assert.equal((await client.get('/api/music/file/test.wav')).status(), 404);
  assert.equal((await fetch(preview.url + media.url)).status, 404);
  const state = await (await client.get('/_published/state.json')).text();
  assert.doesNotMatch(state, /private-friend@example|reader@example|SESSION_SECRET|ADMIN_PASS/);
  assert.equal((await (await post('/api/build/rollback', {})).json()).ok, true);
  assert.equal((await get('/api/public/site-stats')).since, '2020-01-01');
  assert.equal((await get('/api/public/playlist')).tracks[0].title, '旧歌曲');
  assert.equal((await client.get('/api/music/file/test.wav')).status(), 200);
  assert.equal((await fetch(preview.url + media.url)).status, 200);
  assert.equal((await (await post('/api/public/twikoo', { event: 'COMMENT_GET', url: '/notes/' })).json()).data.length, 0);
});
